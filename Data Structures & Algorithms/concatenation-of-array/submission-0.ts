class Solution {
    /**
     * @param {number[]} nums
     * @return {number[]}
     */
    getConcatenation(nums: number[]): number[] {
                        let newArr = [...nums]
                                let i: number
                                        for(i=0; i<nums.length; i++){
                                                    newArr.push(nums[i])
                                                            }
                                                                    return newArr
                                                                        }
    }